window.DK_LANG = "en";

window.t = function t(key, vars) {
  const dict = window.DK_I18N[window.DK_LANG] || window.DK_I18N.en;
  let s = dict[key] ?? window.DK_I18N.en[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      s = s.replaceAll(`{${k}}`, String(v));
    });
  }
  return s;
};

window.applyI18n = function applyI18n() {
  document.documentElement.lang = window.DK_LANG;
  document.title = window.t("meta.title");
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const mode = el.getAttribute("data-i18n-mode") || "text";
    const val = window.t(key);
    if (mode === "html") el.innerHTML = val;
    else if (mode === "placeholder") el.setAttribute("placeholder", val);
    else if (mode === "title") el.setAttribute("title", val);
    else el.textContent = val;
  });
  document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
    btn.classList.toggle("is-active", btn.getAttribute("data-lang-btn") === window.DK_LANG);
  });
};
